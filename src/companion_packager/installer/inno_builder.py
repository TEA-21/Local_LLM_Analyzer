"""Inno Setup script generator and Windows installer / portable packager."""

import os
import shutil
import subprocess
import zipfile
from pathlib import Path


def find_iscc() -> Path | None:
    """Search for Inno Setup Compiler (iscc.exe) on the host system."""
    which_iscc = shutil.which("iscc") or shutil.which("iscc.exe")
    if which_iscc:
        return Path(which_iscc)

    candidates = [
        Path(r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe"),
        Path(r"C:\Program Files\Inno Setup 6\ISCC.exe"),
    ]

    localappdata = os.environ.get("LOCALAPPDATA")
    if localappdata:
        candidates.append(Path(localappdata) / "Programs" / "Inno Setup 6" / "ISCC.exe")

    prog_files = os.environ.get("PROGRAMFILES")
    if prog_files:
        candidates.append(Path(prog_files) / "Inno Setup 6" / "ISCC.exe")

    prog_files_x86 = os.environ.get("ProgramFiles(x86)")
    if prog_files_x86:
        candidates.append(Path(prog_files_x86) / "Inno Setup 6" / "ISCC.exe")

    for c in candidates:
        if c.exists():
            return c

    return None


def generate_inno_script(
    bundle_dir: Path,
    output_iss_path: Path,
    app_name: str = "Agent Companion",
    app_version: str = "0.1.0",
) -> Path:
    """
    Generate a valid Inno Setup .iss compilation script.
    Includes [Setup], [Files], [Icons], and [Run] sections.
    """
    bundle_dir = Path(bundle_dir).resolve()
    output_iss_path = Path(output_iss_path).resolve()
    output_iss_path.parent.mkdir(parents=True, exist_ok=True)

    # Inno Setup paths must use backslashes on Windows
    source_dir_str = str(bundle_dir).replace("/", "\\")
    output_dir_str = str(output_iss_path.parent).replace("/", "\\")

    iss_content = f"""; Inno Setup Script generated by companion-packager
#define SourceDir "{source_dir_str}"
#define AppName "{app_name}"
#define AppVersion "{app_version}"

[Setup]
AppName={{#AppName}}
AppVersion={{#AppVersion}}
DefaultDirName={{localappdata}}\\Programs\\{{#AppName}}
PrivilegesRequired=lowest
OutputBaseFilename=AgentCompanion-Installer
OutputDir={output_dir_str}
Compression=lzma2/max
SolidCompression=yes
DisableProgramGroupPage=yes

[Files]
Source: "{{#SourceDir}}\\*"; DestDir: "{{app}}"; Flags: ignoreversion recursesubdirs createallsubdirs

[Icons]
Name: "{{autoprograms}}\\{{#AppName}}"; Filename: "{{app}}\\start_companion.bat"
Name: "{{autodesktop}}\\{{#AppName}}"; Filename: "{{app}}\\start_companion.bat"

[Run]
Filename: "{{app}}\\runtime\\python.exe"; Parameters: "-m pip install --no-index --find-links=\"\"{{app}}\\wheels\"\" shared_contracts model_runtime security_server document_pipeline agent_tooling companion_packager"; Flags: runhidden waituntilterminated
Filename: "{{app}}\\start_companion.bat"; Description: "{{cm:LaunchProgram,{{#StringChange(AppName, '&', '&&')}}}}"; Flags: nowait postinstall skipifsilent
"""
    output_iss_path.write_text(iss_content, encoding="utf-8")
    return output_iss_path


def build_windows_installer(
    bundle_dir: Path,
    output_dir: Path,
    app_name: str = "Agent Companion",
    app_version: str = "0.1.0",
) -> Path:
    """
    Build Windows installer using Inno Setup (iscc.exe).
    If iscc.exe is not available or compilation fails, falls back to creating
    AgentCompanion-Windows-Portable.zip with setup launchers.
    """
    bundle_dir = Path(bundle_dir).resolve()
    output_dir = Path(output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    iss_path = output_dir / "AgentCompanionSetup.iss"
    generate_inno_script(bundle_dir, iss_path, app_name, app_version)

    iscc_bin = find_iscc()
    if iscc_bin:
        try:
            res = subprocess.run(
                [str(iscc_bin), str(iss_path)],
                capture_output=True,
                text=True,
            )
            if res.returncode == 0:
                expected_installer = output_dir / "AgentCompanion-Installer.exe"
                if expected_installer.exists():
                    return expected_installer
                # Search for any produced exe
                exe_candidates = list(output_dir.glob("*.exe"))
                if exe_candidates:
                    exe_candidates.sort(key=lambda p: p.stat().st_mtime, reverse=True)
                    return exe_candidates[0]
        except Exception:
            pass

    # Fallback to portable zip distribution
    # Ensure bootstrap scripts exist in bundle
    run_setup_bat = bundle_dir / "run_setup.bat"
    if not run_setup_bat.exists():
        run_setup_bat.write_text(
            "@echo off\r\n"
            "setlocal enabledelayedexpansion\r\n"
            "echo [Agent Companion Setup] Installing offline runtime dependencies...\r\n"
            '"%~dp0runtime\\python.exe" -m pip install --no-index --find-links="%~dp0wheels" shared_contracts model_runtime security_server document_pipeline agent_tooling companion_packager\r\n'
            "if %ERRORLEVEL% neq 0 (\r\n"
            "    echo [ERROR] Failed to install offline packages. Exiting.\r\n"
            "    exit /b %ERRORLEVEL%\r\n"
            ")\r\n"
            '"%~dp0runtime\\python.exe" -m companion_packager.cli install --install-dir "%~dp0." --non-interactive\r\n'
            "exit /b %ERRORLEVEL%\r\n",
            encoding="utf-8",
        )

    install_bat = bundle_dir / "install.bat"
    if not install_bat.exists():
        install_bat.write_text(
            '@echo off\r\ncall "%~dp0run_setup.bat"\r\n',
            encoding="utf-8",
        )

    start_companion_bat = bundle_dir / "start_companion.bat"
    if not start_companion_bat.exists():
        start_companion_bat.write_text(
            "@echo off\r\n"
            'for /F "usebackq eol=# tokens=1* delims==" %%i in ("%~dp0agent_companion.env") do (\r\n'
            '    set "%%i=%%~j"\r\n'
            ")\r\n"
            '"%~dp0runtime\\python.exe" "%~dp0start_companion.py"\r\n',
            encoding="utf-8",
        )

    zip_path = output_dir / "AgentCompanion-Windows-Portable.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for file_path in sorted(bundle_dir.rglob("*")):
            if file_path.is_file():
                rel_path = file_path.relative_to(bundle_dir)
                zf.write(file_path, arcname=str(rel_path))

    return zip_path
